export function formatCompareCell(cell: CompareCell): string {
  if (typeof cell === "boolean") return cell ? "Yes" : "—";
  return cell;
}

/** Compact perk list for a single rank product page. */
export function perksForRank(rank: CompareRank) {
  return COMPARE_PERKS.map((perk) => ({
    label: perk.label,
    tip: perk.tip,
    value: formatCompareCell(perk.cells[rank]),
    unlocked: perk.cells[rank] !== false,
  })).filter((perk) => perk.unlocked);
}

export function featuredCompareRank(): CompareRank {
  return "singularity";
}
