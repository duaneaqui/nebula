/** Paid ranks only — Drifter / everyone-Y commands are left off the compare board. */
export const COMPARE_RANKS = PAID_RANKS;
export type CompareRank = PaidRank;

/** true = check, false = X, string = amount or short label */
export type CompareCell = boolean | string;

export type ComparePerk = {
  id: string;
  label: string;
  tip: string;
  cells: Record<CompareRank, CompareCell>;
};

function row(
  id: string,
  label: string,
  tip: string,
  voyager: CompareCell,
  nova: CompareCell,
  pulsar: CompareCell,
  quasar: CompareCell,
  singularity: CompareCell,
): ComparePerk {
  return {
    id,
    label,
    tip,
    cells: { voyager, nova, pulsar, quasar, singularity },
  };
}

